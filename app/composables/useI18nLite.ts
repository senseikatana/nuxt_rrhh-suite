export function useI18nLite() {
  const { locale } = usePreferences()

  function t(key: string): string {
    const table = MESSAGES[locale.value as AppLocale] ?? MESSAGES.es
    return table[key] ?? MESSAGES.es[key] ?? key
  }

  return { t, locale }
}
